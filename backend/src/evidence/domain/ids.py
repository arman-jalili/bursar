"""Evidence identifiers — one NewType each, so envelopes and anchors cannot be swapped.

Canonical: docs/architecture/modules/evidence.md#components
Reference: docs/contracts/evidence-contract-freeze.md §2.1

`EnvelopeId` and `AnchorId` are opaque strings, but a request that confuses them is a real bug:
`GET /v1/evidence/{id}` keys on the envelope, `GET /v1/evidence/{id}/anchor` keys on the anchor
record, and the type checker catches the mix-up for free. `EventId` is the publisher's delivery
identity, reused for the idempotency key `(event_id, handler)` (E-4).
"""

from __future__ import annotations

from typing import NewType

__all__ = ["AnchorId", "EnvelopeId", "EventId", "new_id"]

EnvelopeId = NewType("EnvelopeId", str)
AnchorId = NewType("AnchorId", str)
EventId = NewType("EventId", str)


def new_id() -> str:
    """Fresh opaque identifier (uuid4 hex), generated by the envelope/anchor factories.

    The one non-stub in Phase A: a uuid factory is not behaviour, and stubbing it would force every
    test to invent identifiers that the aggregate then has to accept.
    """
    import uuid

    return uuid.uuid4().hex
