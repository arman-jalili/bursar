"""`RigorixCommandAdapter` — the `PaymentExecutor` port over Rigorix's governed execution (SC-2).

Canonical: .pi/architecture/modules/settlement.md#ports-infrastructure-adapters
Reference: docs/contracts/settlement-contract-freeze.md §2.8 (SC-2)

Why the command text is a module constant
-----------------------------------------
SC-2 says the dispatch path is *generated by code*, never supplied by a caller. The adapter therefore
has one command template, `DISPATCH_COMMAND`, and renders it from `order.command_params()` — a method
that itself takes no arguments. There is no parameter, field or header anywhere in this file that would
let a caller name a command, a payee or an amount: the order is the only input.

How a dispatch runs (verified against a live `rigorix-server`)
--------------------------------------------------------------
1. `ensure_template(order)` creates/overwrites the one template named by `settings.rigorix_run_template`
   whose single `run_command` step carries the rendered command. `created_at`/`updated_at` are required
   by the server even though the SDK's `TemplateCreateParams` does not list them.
2. `execute(order)` runs that template with `execution_id = order.id` (the settlement order id, so the
   audit trail and the order are the same identity).
3. A `Completed` run is a `CommandAck` carrying the execution id and the host's `audit_uri`. A `Failed`
   run — including the boundary refusal Rigorix returns when the server declares no sandbox — is a
   `SettlementRefusal` carrying the step's `error` **verbatim**. Nothing is swallowed, and nothing that
   did not complete is reported as accepted.

Transport failures are refusals, never silent successes: a timeout, a JSON-RPC error, a malformed
answer or an incompatible API version all raise `SettlementRefusal`. The SDK is synchronous (urllib), so
every call goes through `asyncio.to_thread`; the async timeout is enforced with `asyncio.wait_for` on
top of the transport's own timeout.
"""

from __future__ import annotations

import asyncio
from collections.abc import Mapping
from datetime import UTC, datetime
from typing import Any, Protocol

from rigorix_verifier.client import Client, ClientError, HTTPTransport  # type: ignore[import-untyped]

from src.settlement.domain.errors import SettlementRefusal
from src.settlement.domain.ports import CommandAck
from src.settlement.domain.settlement_order import SettlementOrder
from src.shared.domain.errors import ErrorCode, RefusalError
from src.shared.infrastructure.config import Settings

__all__ = ["DISPATCH_COMMAND", "RigorixClient", "RigorixCommandAdapter"]

#: The ONLY dispatch command text in this context (SC-2). Rendered from `order.command_params()`.
#: Changing this constant is a settlement behaviour change, not configuration: the command path is the
#: code-generated contract, and the params come from the frozen order, never from a request.
DISPATCH_COMMAND = (
    "payments.dispatch"
    " --intent-id {intent_id}"
    " --invoice-id {invoice_id}"
    " --payee {payee_address}"
    " --amount-micro-usdc {amount_usdc}"
    " --bank-digest {bank_digest}"
    " --nullifier {nullifier}"
    " --chain-id {chain_id}"
    " --new-payee {is_new_payee}"
    " --owner-signature-required {requires_owner_signature}"
)

#: The completed status the host reports for a run whose steps all succeeded.
_COMPLETED = "completed"

_TEMPLATE_DESCRIPTION = (
    "Bursar settlement dispatch. One run_command step whose command is generated by settlement code "
    "from the frozen order (SC-2). Created and overwritten per dispatch so the command can never be "
    "supplied by a caller."
)


class RigorixClient(Protocol):
    """The slice of `rigorix_verifier.client.Client` this adapter uses.

    Declared so a test can pass a fake with the same call surface instead of reaching the network — and
    so the adapter cannot quietly start depending on a method the fake contract does not pin.
    """

    def version(self) -> Any: ...

    def template_create(self, params: Any) -> Any: ...

    def run(self, params: Any) -> Any: ...


def _rfc3339_now() -> str:
    """RFC3339, seconds precision — the shape the host validates for `created_at`/`updated_at`."""
    return datetime.now(UTC).replace(microsecond=0).isoformat().replace("+00:00", "Z")


def _as_mapping(value: object) -> Mapping[str, object]:
    if isinstance(value, Mapping):
        return value
    raise SettlementRefusal(
        ErrorCode.CONFLICT,
        "Rigorix answered with a non-object result; nothing can be concluded from it.",
        details={"reason": "malformed_result"},
    )


def _step_error(result: Mapping[str, object]) -> str:
    """The first failing step's error, verbatim — Rigorix's refusal is the evidence, not a summary."""
    steps = result.get("steps")
    if isinstance(steps, list):
        for step in steps:
            if not isinstance(step, Mapping):
                continue
            error = step.get("error")
            if error:
                return str(error)
    return ""


class RigorixCommandAdapter:
    """`PaymentExecutor` over one Rigorix server (SC-2, SC-3 evidence)."""

    def __init__(
        self,
        settings: Settings,
        *,
        client: RigorixClient | None = None,
    ) -> None:
        self._settings = settings
        self._client = client or self._build_client(settings)
        self._handshaken = False
        self._handshake_lock = asyncio.Lock()

    # ── construction ────────────────────────────────────────────────────────
    @staticmethod
    def _build_client(settings: Settings) -> Client:
        """The real client. Local mode needs no auth; the timeout is the configured RPC timeout."""
        return Client(
            HTTPTransport(
                f"{settings.rigorix_base_url}/rpc",
                timeout=settings.rigorix_rpc_timeout_seconds,
            )
        )

    @property
    def template_name(self) -> str:
        """The one template this adapter creates and runs (operational knob, see the runbook)."""
        return self._settings.rigorix_run_template

    @property
    def command(self) -> str:
        """The command text this build dispatches — the module constant, not an instance field."""
        return DISPATCH_COMMAND

    # ── executor ────────────────────────────────────────────────────────────
    async def ensure_template(self, order: SettlementOrder) -> None:
        """Create/overwrite the dispatch template for **this** order (SC-2).

        `overwrite=True` is deliberate: the template name is fixed configuration, and re-creating it
        with the order's own generated command is what keeps "one template" and "never a caller's
        command" true at the same time. A stale template would silently dispatch the previous order's
        params, which is worse than a per-dispatch write.
        """
        await self._handshake()
        params = order.command_params()
        command = DISPATCH_COMMAND.format(**params)
        timestamp = _rfc3339_now()
        plan: dict[str, object] = {
            "name": self.template_name,
            "description": _TEMPLATE_DESCRIPTION,
            # Required by the server though absent from `TemplateCreateParams`.
            "created_at": timestamp,
            "updated_at": timestamp,
            "steps": [
                {
                    "name": "dispatch",
                    "tool": "run_command",
                    "parameters": {"command": command},
                    "requires_approval": False,
                    "description": f"Generated dispatch command for order {order.id} (SC-2).",
                }
            ],
        }
        await self._call(
            "template.create",
            {"name": self.template_name, "plan": plan, "overwrite": True},
        )

    async def execute(self, order: SettlementOrder) -> CommandAck:
        """Run the fixed dispatch command for this order, or refuse with the host's reason (SC-2)."""
        await self.ensure_template(order)
        result = _as_mapping(
            await self._call(
                "run",
                {"template_name": self.template_name, "execution_id": str(order.id)},
            )
        )
        status = str(result.get("status", ""))
        execution_id = str(result.get("execution_id") or order.id)
        audit_uri = str(result.get("audit_uri") or "")

        if status.lower() == _COMPLETED:
            return CommandAck(
                command_ref=order.command_ref,
                accepted=True,
                execution_id=execution_id,
                audit_uri=audit_uri,
            )

        # A Failed run — including the `run_command` refusal a server without a declared sandbox
        # returns — is a refusal, and the step's error is surfaced verbatim so an operator reads the
        # host's own words instead of a paraphrase.
        reason = _step_error(result) or f"Rigorix ended the run with status {status or 'unknown'}."
        raise SettlementRefusal(
            ErrorCode.CONFLICT,
            reason,
            details={
                "execution_id": execution_id,
                "status": status or "unknown",
                **({"audit_uri": audit_uri} if audit_uri else {}),
            },
        )

    # ── transport ───────────────────────────────────────────────────────────
    async def _handshake(self) -> None:
        """Negotiate the protocol version once (the SDK refuses a major mismatch itself)."""
        if self._handshaken:
            return
        async with self._handshake_lock:
            if self._handshaken:
                return
            await self._call("version")
            self._handshaken = True

    async def _call(self, method: str, params: object | None = None) -> object:
        """Call the blocking client off the event loop and turn every failure into a refusal."""

        def invoke() -> object:
            if method == "version":
                return self._client.version()
            if method == "template.create":
                return self._client.template_create(params)
            return self._client.run(params)

        try:
            return await asyncio.wait_for(
                asyncio.to_thread(invoke),
                timeout=self._settings.rigorix_rpc_timeout_seconds,
            )
        except TimeoutError as exc:
            raise SettlementRefusal(
                ErrorCode.CONFLICT,
                (
                    "Rigorix did not answer within "
                    f"{self._settings.rigorix_rpc_timeout_seconds:g}s; the dispatch is refused, "
                    "nothing is assumed to have run."
                ),
                details={"reason": "rigorix_timeout", "method": method},
            ) from exc
        except (ClientError, OSError) as exc:
            raise SettlementRefusal(
                ErrorCode.CONFLICT,
                f"Rigorix call {method!r} failed: {exc}",
                details={"reason": "rigorix_transport", "method": method},
            ) from exc
        except RefusalError:
            raise
