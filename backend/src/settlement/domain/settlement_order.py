"""SettlementOrder — the immutable executable form of an allowed intent (frozen).

Canonical: .pi/architecture/modules/settlement.md#aggregate-settlementorder
Reference: docs/contracts/settlement-contract-freeze.md (SC-1 … SC-4, SC-9)

    SC-1  creatable only from a determination whose verdict permits dispatch
    SC-2  payee address, amount and nullifier are copied from the intent and immutable afterwards
    SC-3  the tx hash is persisted BEFORE broadcast; an order never gets a second hash
    SC-4  an order concludes exactly once; a concluded order cannot be re-concluded or reset
    SC-6  a revert is terminal and maps to a refusal, never to a retry
    SC-9  the amount handed to the chain equals the signed intent amount

One contract decision is recorded here rather than in prose: `PAYMENT_COMMAND` is a **ClassVar**, not a
dataclass field. The module doc stub shows `command_ref` as a field with a default, which would let a
caller write `SettlementOrder(..., command_ref="payments.anything")` — precisely what SC-2's sibling
rule (module AC #2) says must be impossible. A ClassVar means there is no constructor argument and no
instance field to taint; the value is the module constant or nothing.

`mark_submitted` takes the **signed** amount as a second argument. That is not ceremony: it is the only
place where "what the chain will move" and "what the owner signed" are both in hand, so SC-9 is checked
there (`AmountIntegrityViolation`) instead of being asserted in a comment.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import ClassVar

from src.authority.domain.ids import IntentId
from src.mandate.domain.values import PayeeAddress
from src.settlement.domain.chain_receipt import ChainReceipt
from src.settlement.domain.ids import OrderId
from src.settlement.domain.values import ChainNetwork, Nullifier, SettlementStatus
from src.settlement.domain.views import DeterminationView, PaymentIntentView
from src.shared.domain.aggregate import AggregateRoot
from src.shared.domain.money import Money

__all__ = ["PAYMENT_COMMAND", "SettlementOrder"]

#: The command path is a module constant, generated by code — never by an LLM, never by a caller.
PAYMENT_COMMAND = "payments.dispatch"


@dataclass(eq=False)
class SettlementOrder(AggregateRoot):
    """An allowed intent made executable. Identity persists; `status` only moves forward.

    `tx_hash` is the write-ahead record: it is set by `mark_submitted` and survives a crash. It is
    `None` while `ORDERED` and never `None` afterwards — an order that reached the chain without a
    persisted hash would be a payment nobody can re-poll (SC-3).
    """

    id: OrderId
    intent_id: IntentId
    invoice_id: str
    payee_address: PayeeAddress
    amount: Money
    nullifier: Nullifier
    network: ChainNetwork
    status: SettlementStatus
    tx_hash: str | None = None

    #: The fixed dispatch path. A ClassVar, so no caller can supply one (SC-2 / module AC #2).
    command_ref: ClassVar[str] = PAYMENT_COMMAND

    @classmethod
    def order(
        cls,
        intent: PaymentIntentView,
        network: ChainNetwork,
        determination: DeterminationView,
    ) -> SettlementOrder:
        """Build the order from an allowed intent, or refuse and persist nothing (SC-1).

        Raises:
            DispatchWithoutAuthority: the determination's verdict does not permit dispatch (SC-1). No
                order object exists afterwards — refusal has no side effect.
        """
        raise NotImplementedError("SC-1 — see module doc")

    def command_params(self) -> dict[str, object]:
        """Structured params for `run_command`, generated here and never accepted from a caller (SC-2).

        The command path is `PAYMENT_COMMAND`; the amount is this order's frozen `amount.micro_usdc`
        (SC-9); the address and digest are the ones copied from the intent (SC-2). There is deliberately
        no parameter list: there is nothing a caller could be trusted to pass.
        """
        raise NotImplementedError("SC-2 — see module doc")

    def mark_submitted(self, tx_hash: str, signed_amount: Money) -> None:
        """Record the tx hash **before** broadcast, and prove the amount is the signed one (SC-3, SC-9).

        Raises:
            IllegalTransition: the order is not `ORDERED` — a concluded or already-submitted order has
                no legal path back to submission (SC-4, SC-6).
            SecondTransactionRefused: a different hash is offered for an order that already has one; a
                new hash means a new nonce and a second payment (SC-3).
            AmountIntegrityViolation: `signed_amount` differs from the order's frozen amount (SC-9).
        """
        raise NotImplementedError("SC-3 — see module doc")

    def conclude(self, receipt: ChainReceipt) -> None:
        """Move to `CONFIRMED` or `REVERTED`, once (SC-4, SC-6, SC-7).

        Raises:
            OrderAlreadyConcluded: the order is already `CONFIRMED`, `REVERTED` or `ABANDONED` (SC-4).
                A second conclusion is a bug, not an idempotent no-op: silently accepting it would let a
                replayed settlement look normal.
            SettlementNotFinal: fewer confirmations than `network.confirmations_required`; no cap commit
                may happen yet (SC-7).
            IllegalTransition: the order never reached the chain, so it has no receipt to conclude (SC-3).
        """
        raise NotImplementedError("SC-4 — see module doc")
