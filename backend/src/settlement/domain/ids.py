"""Settlement identifiers — one NewType each, so an order and its receipt cannot be swapped.

Canonical: docs/architecture/modules/settlement.md#components
Reference: docs/contracts/settlement-contract-freeze.md §2

`OrderId`, `ReceiptId` and `AnchorId` are all opaque strings, but the endpoints key on different ones
(`/v1/orders/{id}`, `/v1/orders/{id}/receipt`, `/v1/anchors`) and the outbox carries `order_id` next to
`tx_hash`. Confusing them is a realistic bug, and the type checker catches it for free.

`IntentId` is Authority's — re-exported rather than re-declared so both contexts address the same intent
value (the context map's `intent_id` contract).
"""

from __future__ import annotations

import uuid
from typing import NewType

from src.authority.domain.ids import IntentId

__all__ = ["AnchorId", "IntentId", "OrderId", "ReceiptId", "new_id"]

OrderId = NewType("OrderId", str)
ReceiptId = NewType("ReceiptId", str)
AnchorId = NewType("AnchorId", str)


def new_id() -> str:
    """Fresh opaque identifier (uuid4 hex), generated by the aggregate factories.

    The only body in this package allowed to do something: identifier generation is not behaviour,
    and stubbing it would force every test to invent ids.
    """
    return uuid.uuid4().hex
