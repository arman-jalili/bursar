"""Identifiers — one NewType per aggregate, so ids cannot be mixed up.

Canonical: .pi/architecture/modules/mandate.md#components
Reference: .pi/architecture/decisions/ADR-002-data-storage-strategy.md

`NewType` rather than plain `str`: passing a `PayeeId` where a `HouseholdId` is expected is a
realistic bug in a context with three aggregate roots and three parties, and the type checker
catches it for free. Values are opaque strings (uuid4 hex, generated by the factories through
`src/shared/domain` — never by a repository).
"""

from __future__ import annotations

import uuid
from typing import NewType

__all__ = [
    "AgentId",
    "ConstitutionId",
    "HouseholdId",
    "OwnerId",
    "PayeeId",
    "PayerId",
]

HouseholdId = NewType("HouseholdId", str)
OwnerId = NewType("OwnerId", str)
PayerId = NewType("PayerId", str)
AgentId = NewType("AgentId", str)
PayeeId = NewType("PayeeId", str)
ConstitutionId = NewType("ConstitutionId", str)


def new_id() -> str:
    """A fresh opaque identifier (uuid4 hex).

    Generated by the aggregate factories, never by a repository: an id that appears during
    persistence would mean the aggregate did not own its identity.
    """
    return uuid.uuid4().hex
